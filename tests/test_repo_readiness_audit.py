def _git(args: list[str], cwd: Path) -> None:
    subprocess.run(
        [
            "git",
            "-c",
            "user.name=test",
            "-c",
            "user.email=t@example.com",
            "-c",
            "commit.gpgsign=false",
            *args,
        ],
        cwd=cwd,
        check=True,
        capture_output=True,
    )


def _commit(cwd: Path, message: str) -> None:
    _git(["add", "-A"], cwd)
    _git(["commit", "-m", message, "--no-verify"], cwd)


# ── Clone freshness (L-18) ───────────────────────────────────────────────────


def test_stale_clone_is_detected(tmp_path: Path) -> None:
    """A stale clone is how a remediated file gets resurrected.

    Live jolarca-compliance has NO .github/CODEOWNERS, yet its local clone still
    carries the pre-D-20 version naming mission-org teams. `origin/main` read as
    "in sync" because a remote-tracking ref only moves on fetch.
    """
    origin = tmp_path / "origin.git"
    subprocess.run(
        ["git", "init", "--bare", "-b", "main", str(origin)], check=True, capture_output=True
    )
    seed = _make_repo(tmp_path / "seed", {"README.md": "v1\n"})
    _git(["remote", "add", "origin", str(origin)], seed)
    _git(["push", "origin", "main"], seed)

    clone = tmp_path / "clone"
    subprocess.run(["git", "clone", str(origin), str(clone)], check=True, capture_output=True)

    # Advance the remote behind the clone's back; do NOT fetch in the clone.
    (seed / "README.md").write_text("v2 pushed by someone else\n", encoding="utf-8")
    _commit(seed, "second commit")
    _git(["push", "origin", "main"], seed)

    report = rra.RepoReport(repo="example", local_path=str(clone))
    rra.check_local(report, {}, rra.secret_patterns({}))
    assert any(f.fid == "L-18" for f in report.findings), [f.fid for f in report.findings]
    assert report.facts["remote_branch_exists"] is True


def test_clone_ahead_of_remote_is_not_stale(tmp_path: Path) -> None:
    """The normal pre-push state — local commits the remote lacks — is NOT a
    finding, or the gate would block every first commit it exists to permit."""
    origin = tmp_path / "origin.git"
    subprocess.run(
        ["git", "init", "--bare", "-b", "main", str(origin)], check=True, capture_output=True
    )
    seed = _make_repo(tmp_path / "seed", {"README.md": "v1\n"})
    _git(["remote", "add", "origin", str(origin)], seed)
    _git(["push", "origin", "main"], seed)

    clone = tmp_path / "clone"
    subprocess.run(["git", "clone", str(origin), str(clone)], check=True, capture_output=True)
    (clone / "NEW.md").write_text("local work awaiting push\n", encoding="utf-8")
    _commit(clone, "local commit not yet pushed")

    report = rra.RepoReport(repo="example", local_path=str(clone))
    rra.check_local(report, {}, rra.secret_patterns({}))
    assert not any(f.fid == "L-18" for f in report.findings), [f.fid for f in report.findings]


