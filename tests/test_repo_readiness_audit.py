# ── Verdict logic: "probably fine" is not a verdict ──────────────────────────


def _report(severity: str | None = None, unverified: bool = False) -> object:
    report = rra.RepoReport(repo="example")
    if severity is not None:
        report.add(rra.Finding("T-01", severity, "test", "summary", "evidence", "fix"))
    if unverified:
        report.note_unverified("test check", "could not be performed")
    report.decide()
    return report


