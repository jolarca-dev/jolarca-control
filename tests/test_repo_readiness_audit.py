# ── Policy-driven, not hardcoded ─────────────────────────────────────────────


def test_secret_patterns_come_from_policy() -> None:
    """policy/compliance-gates.yml#gates.secret_scan is the source of truth."""
    gates = {
        "gates": {
            "secret_scan": {
                "implementation": {
                    "custom_patterns": [
                        {
                            "pattern": "jolarca_(live|test)_[a-zA-Z0-9]{32,}",
                            "description": "API keys",
                        }
                    ]
                }
            }
        }
    }
    patterns = rra.secret_patterns(gates)
    assert patterns[0][0] == "jolarca_(live|test)_[a-zA-Z0-9]{32,}"
    # Built-ins are appended, never substituted.
    assert len(patterns) > len(gates["gates"]["secret_scan"]["implementation"]["custom_patterns"])


